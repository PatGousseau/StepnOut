create table public.growth_intakes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  answers jsonb not null default '{}'::jsonb,
  status text not null default 'in_progress'
    check (status in ('in_progress', 'proposed', 'confirmed', 'abandoned')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create table public.growth_plans (
  id uuid primary key default gen_random_uuid(),
  intake_id uuid not null references public.growth_intakes(id) on delete restrict,
  user_id uuid not null references public.profiles(id) on delete cascade,
  version integer not null check (version > 0),
  status text not null default 'proposed'
    check (status in ('proposed', 'active', 'rejected', 'superseded')),
  goal text not null check (char_length(goal) between 1 and 600),
  formulation text not null check (char_length(formulation) between 1 and 1000),
  milestones jsonb not null check (
    jsonb_typeof(milestones) = 'array'
    and jsonb_array_length(milestones) between 3 and 4
  ),
  current_focus text not null check (char_length(current_focus) between 1 and 500),
  first_step jsonb not null check (jsonb_typeof(first_step) = 'object'),
  model_name text not null,
  prompt_version text not null,
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  unique (user_id, version)
);

create unique index growth_plans_one_active_per_user
  on public.growth_plans(user_id)
  where status = 'active';

create table public.growth_plan_evidence (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  intake_id uuid not null references public.growth_intakes(id) on delete restrict,
  plan_id uuid references public.growth_plans(id) on delete set null,
  kind text not null check (kind in ('correction', 'confirmation')),
  content jsonb not null,
  created_at timestamptz not null default now()
);

create table public.growth_event_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  intake_id uuid not null references public.growth_intakes(id) on delete cascade,
  enabled boolean not null default false,
  approximate_location text not null default '',
  travel_radius text not null default '',
  availability text not null default '',
  cost_preference text not null default '',
  accessibility_needs text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.growth_generation_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  intake_id uuid not null references public.growth_intakes(id) on delete cascade,
  request_fingerprint text not null,
  status text not null default 'started'
    check (status in ('started', 'completed', 'failed')),
  created_at timestamptz not null default now(),
  finished_at timestamptz
);

create index growth_generation_requests_user_created_idx
  on public.growth_generation_requests(user_id, created_at desc);
create index growth_generation_requests_fingerprint_idx
  on public.growth_generation_requests(user_id, request_fingerprint, created_at desc);

alter table public.growth_intakes enable row level security;
